
const axios = require("axios");
const Inventory = require("../models/Inventory");
const VendorInventory = require("../models/VendorInventory");
const Part = require("../models/Parts");

const calculateJavaScriptScores = (options, requiredQuantity, partUnitPrice) => {
  const rankedOptions = options.map((option) => {
    const deliveryScore = Math.max(
      0,
      100 - option.estimatedDeliveryHours * 5
    );

    const costScore = Math.max(
      0,
      100 - (option.unitPrice / Math.max(partUnitPrice, 1)) * 20
    );

    const score =
      deliveryScore * 0.5 +
      costScore * 0.2 +
      option.reliabilityScore * 0.3;

    return {
      ...option,
      score: Number(score.toFixed(2)),
      canFulfilEntireQuantity:
        option.availableQuantity >= requiredQuantity,
    };
  });

  rankedOptions.sort((a, b) => b.score - a.score);

  return rankedOptions;
};

const buildCombinedPlan = (rankedOptions, requiredQuantity) => {
  let remainingQuantity = requiredQuantity;
  let totalCost = 0;
  let totalAllocatedQuantity = 0;

  const sources = [];

  for (const option of rankedOptions) {
    if (remainingQuantity <= 0) break;

    const allocatedQuantity = Math.min(
      option.availableQuantity,
      remainingQuantity
    );

    if (allocatedQuantity <= 0) continue;

    const estimatedCost = allocatedQuantity * option.unitPrice;

    sources.push({
      ...option,
      allocatedQuantity,
      estimatedCost: Number(estimatedCost.toFixed(2)),
    });

    totalCost += estimatedCost;
    totalAllocatedQuantity += allocatedQuantity;
    remainingQuantity -= allocatedQuantity;
  }

  return {
    sources,
    totalAllocatedQuantity,
    totalAvailableQuantity: rankedOptions.reduce(
      (total, option) => total + option.availableQuantity,
      0
    ),
    remainingQuantity,
    totalCost: Number(totalCost.toFixed(2)),
    estimatedDeliveryHours: sources.length
      ? Math.max(...sources.map(source => source.estimatedDeliveryHours))
      : 0,
    isFulfilled: remainingQuantity === 0,
  };
};

const findSourceOptions = async (
  dealershipId,
  partId,
  requiredQuantity
) => {
  const part = await Part.findById(partId);

  if (!part) {
    throw new Error("Part not found");
  }

  const sisterStock = await Inventory.find({
    part: partId,
    dealership: { $ne: dealershipId },
  }).populate("dealership");

  const vendorStock = await VendorInventory.find({
    part: partId,
    isAvailable: true,
    availableQuantity: { $gt: 0 },
  }).populate("vendor");

  const options = [];

  for (const stock of sisterStock) {
    const availableQuantity = Math.max(
      0,
      stock.quantity - stock.reservedQuantity
    );

    if (availableQuantity <= 0) continue;

    options.push({
      sourceType: "Sister Dealership",
      sourceId: stock.dealership._id,
      sourceName: stock.dealership.name,
      location: `${stock.dealership.location.city}, ${stock.dealership.location.state}`,
      availableQuantity,
      unitPrice: part.unitPrice,
      estimatedDeliveryHours: 2,
      reliabilityScore: 90,
    });
  }

  for (const stock of vendorStock) {
    options.push({
      sourceType: "Vendor",
      sourceId: stock.vendor._id,
      sourceName: stock.vendor.name,
      location: `${stock.vendor.address.city}, ${stock.vendor.address.state}`,
      availableQuantity: stock.availableQuantity,
      unitPrice: stock.unitPrice,
      estimatedDeliveryHours: stock.estimatedDeliveryHours,
      reliabilityScore: stock.vendor.reliabilityScore,
    });
  }

  let rankedOptions;
  let combinedPlan;

  try {
    const aiServiceUrl =
      process.env.AI_SERVICE_URL || "http://127.0.0.1:8000";

    const response = await axios.post(
      `${aiServiceUrl}/api/v1/sourcing/rank`,
      {
        partUnitPrice: part.unitPrice,
        requiredQuantity,
        options: options.map((option) => ({
          ...option,
          sourceId: String(option.sourceId),
        })),
      },
      {
        timeout: 5000,
      }
    );

    if (
      !response.data.success ||
      !Array.isArray(response.data.options) ||
      !response.data.combinedPlan
    ) {
      throw new Error("Invalid response from AI service");
    }

    const originalSources = new Map(
      options.map((option) => [
        `${option.sourceType}:${String(option.sourceId)}`,
        option.sourceId,
      ])
    );

    const restoreSourceId = (option) => ({
      ...option,
      sourceId:
        originalSources.get(
          `${option.sourceType}:${option.sourceId}`
        ) || option.sourceId,
    });

    rankedOptions = response.data.options.map(restoreSourceId);

    combinedPlan = {
      ...response.data.combinedPlan,
      sources: response.data.combinedPlan.sources.map(restoreSourceId),
    };

    console.log("Sourcing options and combined plan generated by FastAPI.");
  } catch (error) {
    console.warn(
      "AI service unavailable. Using JavaScript scoring fallback:",
      error.message
    );

    rankedOptions = calculateJavaScriptScores(
      options,
      requiredQuantity,
      part.unitPrice
    );

    combinedPlan = buildCombinedPlan(
      rankedOptions,
      requiredQuantity
    );
  }

  return {
    part: {
      id: part._id,
      partNumber: part.partNumber,
      name: part.name,
    },
    requiredQuantity,
    options: rankedOptions,
    combinedPlan,
  };
};

module.exports = { findSourceOptions };
